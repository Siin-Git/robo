import {test,expect,type Page} from '@playwright/test';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import path from 'node:path';
const directory=process.env.E2E_REPLAY_DIR!;
const output=process.env.E2E_REPLAY_OUTPUT??path.join(directory,'screens');
async function signIn(page:Page){
 const account=JSON.parse(readFileSync(path.join(directory,'accounts.json'),'utf8')).accounts[2];
 await page.context().clearCookies();await page.goto('/login');
 await page.getByLabel('이메일',{exact:true}).fill(account.email);
 await page.getByLabel('비밀번호',{exact:true}).fill(account.password);
 await page.getByRole('button',{name:'로그인',exact:true}).click();
 await expect(page).not.toHaveURL(/\/login/);
}
for(const width of [1440,390])test(`competition replay actual engine browser flow ${width}`,async({page})=>{
 mkdirSync(output,{recursive:true});await page.setViewportSize({width,height:width===390?844:1000});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await signIn(page);await page.goto('/portfolio');
 await expect(page.getByRole('region',{name:'테마 적용 전후 Efficient Frontier 위치'})).toBeVisible();
 await expect(page.getByRole('status',{name:'로컬 과거 재생 시연'})).toContainText('READY 15/15');
 await expect(page.getByRole('status',{name:'로컬 과거 재생 시연'})).toContainText('처리 15/15');
 await page.screenshot({path:path.join(output,`portfolio-${width}.png`),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/dashboard');
 await expect(page.getByRole('region',{name:'기록된 평가액'})).toContainText('현금');
 await expect(page.getByRole('region',{name:'운용 원장'})).toContainText('체결');
 await expect(page.getByRole('img',{name:/누적수익률:/})).toBeVisible();
 await expect(page.getByRole('heading',{name:'내 수익은 어디에서 나왔을까요?'})).toBeVisible();
 const own=await(await page.request.get('/api/v1/me/performance/dashboard')).json();
 const ledger=await(await page.request.get('/api/v1/me/performance/ledger')).json();
 expect(own.observations).toBe(10);expect(own.data_kind).toBe('HISTORICAL_REPLAY');
 expect(own.metrics.volatility).toBeNull();expect(ledger.data_kind).toBe('HISTORICAL_REPLAY');
 const before=own.metrics;
 await page.reload();
 await expect(page.getByRole('region',{name:'기록된 평가액'})).toBeVisible();
 expect((await(await page.request.get('/api/v1/me/performance/dashboard')).json()).metrics).toEqual(before);
 await page.getByRole('button',{name:'개별 자산',exact:true}).click();
 await expect(page.getByRole('heading',{name:'자산별 기여도',exact:true})).toBeVisible();
 await page.screenshot({path:path.join(output,`dashboard-${width}.png`),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/ranking');
 await expect(page.getByRole('region',{name:'운용 기록 참여자 순위'}).locator('tbody tr')).toHaveCount(15);
 await expect(page.getByRole('region',{name:'참여자와 CORE 지수 그래프'})).toBeVisible();
 const comp=await(await page.request.get('/api/v1/me/performance/comparison')).json();
 expect(comp.ranked).toBe(15);expect(comp.replay_context.completed).toBe(15);
 const me=await(await page.request.get('/api/v1/me')).json();
 const mine=comp.items.find((r:any)=>r.participant_id===me.participant_id);
 expect(mine.metrics).toEqual(before);
 expect(mine.series.filter((p:any)=>p.personal_index100!==null)).toHaveLength(10);
 expect(mine.series.some((p:any)=>p.personal_index100===null)).toBe(true);
 await page.screenshot({path:path.join(output,`ranking-${width}.png`),fullPage:true});
 await page.getByLabel('순위 기준',{exact:true}).selectOption('mdd');
 await expect(page.getByRole('region',{name:'운용 기록 참여자 순위'})).toContainText('MDD 순위 보류');
 expect((await(await page.request.get('/api/v1/me/performance/comparison?basis=mdd')).json()).ranked).toBe(0);
 await page.getByLabel('순위 기준',{exact:true}).selectOption('volatility');
 expect((await(await page.request.get('/api/v1/me/performance/comparison?basis=volatility')).json()).ranked).toBe(0);
 await page.getByRole('link',{name:'공통 기간의 내 성과·기여도'}).click();
 await expect(page.getByText(/참여자 비교와 같은 공통 관측 기간/)).toBeVisible();
 const common=await(await page.request.get('/api/v1/me/performance/dashboard?comparison=common')).json();
 const contributions=await(await page.request.get('/api/v1/me/performance/contributions?comparison=common')).json();
 expect(common.metrics).toEqual(mine.metrics);expect(contributions.reconciliation.reconciled).toBe(true);
 expect(contributions.cumulative_return).toBe(common.metrics.cumulative_return);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto('/review');
 await expect(page.getByRole('heading',{name:/확정 당시 판단/})).toBeVisible();
 await page.screenshot({path:path.join(output,`review-${width}.png`),fullPage:true});
 const review=await(await page.request.get(`/api/v1/me/decisions/${own.decision_context.pending_decision?.decision_id??own.decision_context.active_decision?.decision_id}/review`)).json();
 expect(JSON.stringify(review)).not.toContain('HISTORICAL_REPLAY');
 await signIn(page);await page.goto('/dashboard');
 expect((await(await page.request.get('/api/v1/me/performance/dashboard')).json()).metrics).toEqual(before);
 expect((await(await page.request.get('/api/v1/me/performance/replay')).json()).replay_context.completed).toBe(15);
 expect(errors).toEqual([]);
 writeFileSync(path.join(output,`verified-${width}.json`),JSON.stringify({observations:own.observations,start:own.start,end:own.end,ranked:comp.ranked,metrics:before,reconciled:contributions.reconciliation.reconciled,dates:comp.dates},null,2));
});
