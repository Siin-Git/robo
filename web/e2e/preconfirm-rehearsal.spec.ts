import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const root=path.resolve(__dirname,'../..'),fixture=process.env.E2E_OPERATIONS_DATA_DIR!;
if(!fixture?.startsWith('/private/tmp/'))throw new Error('Disposable fixture required.');
const accounts=JSON.parse(fs.readFileSync(path.join(fixture,'accounts.json'),'utf8')).accounts;
const evidence=path.join(root,'docs/evidence/preconfirm-rehearsal');
const counts=()=>JSON.parse(execFileSync(path.join(root,'.venv/bin/python'),['scripts/seed_verification_ui_fixture.py','--directory',fixture,'--mode','counts'],{cwd:root,encoding:'utf8'}));
for(const [index,choice] of ['base','themes'].entries())test(`real API: compare before confirmation and explicitly choose ${choice}`,async({page})=>{
  fs.mkdirSync(evidence,{recursive:true});
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/login');await page.getByLabel('이메일').fill(accounts[index].email);await page.getByLabel('비밀번호').fill(accounts[index].password);await page.getByRole('button',{name:'로그인',exact:true}).click();await expect(page).toHaveURL(/dashboard|setup\/portfolio/);
  const old=(await(await page.request.get('/api/v1/me/decisions')).json()).items;
  await page.goto('/setup/portfolio?step=risk');
  await page.getByRole('button',{name:'다음: 투자 인사이트 반영'}).click();
  const ai=page.getByRole('button',{name:/^인공지능 선택( 해제)?$/});
  await expect(ai).toBeVisible();
  if(await ai.getAttribute('aria-pressed')!=='true')await ai.click();
  await page.getByRole('button',{name:'다음: 변경 전·후 비교'}).click();
  await expect(page.getByRole('heading',{name:'두 구성 비교'})).toBeVisible();
  const before=counts();
  await expect(page.getByRole('button',{name:'선택한 테마 반영해 확정'})).toBeEnabled();
  await page.getByLabel('비교 기간').selectOption('2022');
  await page.getByLabel('가정 투자금').selectOption('1000000');
  const draft=await(await page.request.get('/api/v1/me/onboarding/draft')).json();
  const request={frontier_id:draft.frontier_id,theme_ids:draft.theme_ids,period:'2022',initial_amount:1000000};
  const preview=await(await page.request.post('/api/v1/me/onboarding/rehearsal',{data:request})).json();
  expect(preview.status).toBe('AVAILABLE');
  await expect(page.getByRole('region',{name:'확정 전 과거 비교'})).toContainText(`${(preview.personalized.max_drawdown*100).toFixed(2)}%`);
  expect(counts()).toEqual(before);
  expect((await(await page.request.get('/api/v1/me/decisions')).json()).items).toEqual(old);
  await page.getByRole('button',{name:'평가액',exact:true}).click();await page.getByRole('button',{name:'낙폭',exact:true}).click();
  if(index===0){
    await page.screenshot({path:path.join(evidence,'comparison-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(evidence,'comparison-mobile.png'),fullPage:true});
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.setViewportSize({width:320,height:740});await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.setViewportSize({width:1440,height:1050});
  }
  await page.getByText('비중·예상 위험 상세',{exact:false}).click();
  await expect(page.getByRole('heading',{name:'예상 변동성의 변화'})).toBeVisible();
  if(index===0){await page.setViewportSize({width:320,height:740});await page.screenshot({path:path.join(evidence,'details-mobile.png'),fullPage:true});
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await page.setViewportSize({width:1440,height:1050});}
  const reason=`격리 테스트: ${choice} 선택 근거. 실제 운용 판단 아님.`;
  await expect(page.getByLabel('확정 전 선택 이유')).not.toBeVisible();
  await page.getByText(/^선택 이유 (남기기|보기·수정)/).click();
  await page.getByLabel('확정 전 선택 이유').fill(reason);
  await page.getByRole('button',{name:choice==='base'?'기본 구성으로 확정':'선택한 테마 반영해 확정',exact:true}).click();
  await expect(page).toHaveURL(/\/portfolio$/);
  const decisions=(await(await page.request.get('/api/v1/me/decisions')).json()).items;
  expect(decisions).toHaveLength(old.length+1);expect(decisions.slice(1)).toEqual(old);
  const selected=decisions[0];expect(selected.reason).toBe(reason);
  expect(selected.weights).toEqual(preview[choice==='base'?'base':'personalized'].weights);
  const after=counts();expect(after.portfolio_decisions).toBe(before.portfolio_decisions+1);
  for(const key of ['orders','trades','nav_daily','scheduled_jobs','portfolio_choices'])expect(after[key]).toBe(before[key]);
  await page.reload();
  expect((await(await page.request.get('/api/v1/me/decisions')).json()).items[0]).toEqual(selected);
  expect(errors).toEqual([]);
});
