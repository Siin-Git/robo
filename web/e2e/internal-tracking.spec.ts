import {test,expect,type Page} from '@playwright/test';
import {readFileSync,mkdirSync} from 'node:fs';
import path from 'node:path';

// Only the explicitly supplied, disposable LOCAL VALIDATION directory is used.
const directory=process.env.E2E_TRACKING_DIR!;
const fixture=JSON.parse(readFileSync(path.join(directory,'internal-accounts.json'),'utf8'));
const replay=JSON.parse(readFileSync(path.join(directory,'run.json'),'utf8'));
const output=process.env.E2E_TRACKING_OUTPUT!;
async function login(page:Page,account:{email:string;password:string}){
 await page.context().clearCookies();await page.goto('/login');
 await page.getByLabel('이메일',{exact:true}).fill(account.email);
 await page.getByLabel('비밀번호',{exact:true}).fill(account.password);
 await page.getByRole('button',{name:'로그인',exact:true}).click();
 await expect(page).not.toHaveURL(/\/login/,{timeout:30_000});
}
for(const width of [1440,390])test(`internal tracking authority, persistence and replay boundary ${width}`,async({page})=>{
 expect(fixture.validation_only).toBe(true);
 mkdirSync(output,{recursive:true});await page.setViewportSize({width,height:width===390?844:1000});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await login(page,fixture.admin);await page.goto('/admin');
 await page.getByRole('link',{name:'내부 판단 추적 · 자산별 관측과 revision 검토',exact:true}).click();
 await expect(page.getByRole('heading',{name:'내부 판단 추적',level:1,exact:true})).toBeVisible();
 await page.getByLabel('추적할 판단').selectOption(fixture.new_decision_id);
 await expect(page.getByText(/확정 당시 Frontier 좌표 \(50개\)/)).toBeVisible();
 const frontier=page.locator('details').filter({has:page.locator('summary').filter({hasText:'확정 당시 Frontier 좌표'})});
 await frontier.locator('summary').click();await expect(frontier.getByRole('row')).toHaveCount(51);
 expect(await page.getByLabel('로컬 과거 재생 시연').count()).toBe(0);
 await expect(page.getByText(/과거 재현은 3·6개월 관측에서 제외합니다/)).toBeVisible();
 const endpoint=`/api/v1/admin/tracking/${fixture.new_decision_id}`;
 const before=await(await page.request.get(endpoint)).json();
 expect(before.snapshot_status).toBe('RECORDED');expect(before.snapshot.frontier.points).toHaveLength(50);
 expect(before.actual_ledger.observations).toBe(0);
 expect(before.assets.every((a:any)=>a.comparison.difference===null)).toBe(true);
 await page.getByLabel('추적할 자산').selectOption('theme:ai');
 await page.getByLabel('검토 방향').selectOption('REVISION_REVIEW');
 const reason=`LOCAL VALIDATION ${width} ${Date.now()}: 최초 전망 정의와 실제 관측 부족을 검토함`;
 await page.getByLabel('검토 근거').fill(reason);
 await page.getByRole('button',{name:'검토 기록 저장',exact:true}).click();
 await expect(page.getByText('내부 검토 기록을 저장했습니다.',{exact:true})).toBeVisible();
 await expect(page.getByRole('listitem').getByText(reason,{exact:true})).toBeVisible();
 const saved=await(await page.request.get(endpoint)).json();
 expect(saved.snapshot).toEqual(before.snapshot);expect(saved.actual_ledger).toEqual(before.actual_ledger);
 expect(saved.reviews.filter((r:any)=>r.reason===reason)).toHaveLength(1);
 await page.getByRole('button',{name:'검토 기록 저장',exact:true}).click();
 await page.reload();await page.getByLabel('추적할 판단').selectOption(fixture.new_decision_id);
 await expect(page.getByRole('listitem').getByText(reason,{exact:true})).toBeVisible();
 expect((await(await page.request.get(endpoint)).json()).reviews.filter((r:any)=>r.reason===reason)).toHaveLength(1);
 await page.screenshot({path:path.join(output,`tracking-${width}.png`),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await login(page,fixture.admin);await page.goto('/admin/tracking');
 await page.getByLabel('추적할 판단').selectOption(fixture.new_decision_id);
 await expect(page.getByRole('listitem').getByText(reason,{exact:true})).toBeVisible();
 const legacy=replay.members[2].decision_id;
 const old=await(await page.request.get(`/api/v1/admin/tracking/${legacy}`)).json();
 expect(old.snapshot).toBeNull();expect(old.actual_ledger.observations).toBe(0);
 expect(old.assets.every((a:any)=>a.observations===0&&a.initial_estimate===null)).toBe(true);
 await login(page,fixture.new_confirmation);
 expect((await page.request.get('/api/v1/admin/tracking')).status()).toBe(403);
 expect((await page.request.get(endpoint)).status()).toBe(403);
 const own=await(await page.request.get('/api/v1/me/decisions')).json();
 expect(JSON.stringify(own)).not.toContain('"internal_tracking"');
 const review=await(await page.request.get(`/api/v1/me/decisions/${fixture.new_decision_id}/review`)).json();
 expect(JSON.stringify(review)).not.toContain(reason);expect(review.actual.observations).toBe(0);
 await page.goto('/admin/tracking');
 await expect(page.getByText(/관리자 권한이 필요합니다/)).toBeVisible();
 expect(await page.getByRole('button',{name:'검토 기록 저장',exact:true}).count()).toBe(0);
 await page.screenshot({path:path.join(output,`denied-${width}.png`),fullPage:true});
 expect(errors).toEqual([]);
});
