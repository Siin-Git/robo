test('real API: loading, request failure and retry never attach old values to new controls', async ({page}) => {
  await login(page);
  await page.goto(`/portfolio/rehearsal?decision_id=${original.decision_id}`);
  await expect(page.getByRole('region', {name: '고점 대비 하락률 그래프'})).toBeVisible();
  let release!: () => void;
  const barrier = new Promise<void>(resolve => {release = resolve;});
  await page.route('**/rehearsal?period=2022*', async route => {await barrier; await route.abort('failed');});
  await page.getByLabel('비교 기간').selectOption('2022');
  await expect(page.getByLabel('Loading')).toBeVisible();
  await expect(page.getByRole('region', {name: '고점 대비 하락률 그래프'})).toHaveCount(0);
  release(); await expect(page.getByRole('main').getByRole('alert')).toContainText('리허설을 불러오지 못했습니다');
  await page.screenshot({path: path.join(evidence, 'request-failure.png'), fullPage: true});
  await page.unroute('**/rehearsal?period=2022*');
  await page.getByRole('button', {name: '다시 조회'}).click();
  await expect(page.getByRole('region', {name: '고점 대비 하락률 그래프'})).toBeVisible();
  await page.getByLabel('가정 투자금').focus(); await expect(page.getByLabel('가정 투자금')).toBeFocused();
  await page.goto('/portfolio/rehearsal');
  await expect(page.getByRole('status')).toContainText('저장된 판단을 선택');
});

test('real API: review retains the scenario, saves only a review record and returns to the same comparison',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  const before=counts();
  await login(page);
  const rehearsal=`/portfolio/rehearsal?decision_id=${original.decision_id}&period=2022&initial_amount=1000000`;
  await page.goto(rehearsal);
  await expect(page.getByLabel('비교 기간')).toHaveValue('2022');
  await expect(page.getByLabel('가정 투자금')).toHaveValue('1000000');
  const response=await(await page.request.get(`/api/v1/me/decisions/${original.decision_id}/rehearsal?period=2022&initial_amount=1000000`)).json();
  await expect(page.getByText(won(response.personalized.end_value),{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'유지·조정 이유 남기기',exact:true}).click();
  await expect(page).toHaveURL(/period=2022&initial_amount=1000000&source=rehearsal/);
  const review=page.url();
  await expect(page.getByRole('heading',{name:'내 선택 다시 살펴보기',level:1})).toBeVisible();
  await expect(page.getByRole('region',{name:'방금 본 리허설'})).toContainText('각 1,000,000원');
  await expect(page.getByRole('region',{name:'방금 본 리허설'})).toContainText(`${(response.personalized.max_drawdown*100).toFixed(2)}%`);
  await expect(page.getByLabel('선택 이유')).toBeVisible();
  await expect(page.getByRole('button',{name:'구성 유지 선택',exact:true})).toBeDisabled();
  expect((await page.getByLabel('선택 이유').boundingBox())!.y).toBeLessThan(800);
  await page.screenshot({path:path.join(evidence,'review-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:path.join(evidence,'review-mobile.png'),fullPage:true});
  const reason='격리 UI 검증: 분산 목적과 하락 폭을 함께 검토. 운영 판단 아님.';
  await page.getByLabel('선택 이유').fill(reason);
  await page.getByRole('button',{name:'구성 유지 선택',exact:true}).click();
  const saved=page.getByRole('status').filter({hasText:'유지 선택을 저장했습니다'});
  await expect(saved).toBeVisible();await expect(saved).toBeFocused();
  const choices=(await(await page.request.get('/api/v1/me/portfolio/choices')).json()).items;
  expect(choices.filter((c:{decision_id:string;reason:string;action:string})=>c.decision_id===original.decision_id&&c.reason===reason&&c.action==='KEEP')).toHaveLength(1);
  expect(counts()).toEqual({...before,portfolio_choices:before.portfolio_choices+1});
  expect((await(await page.request.get('/api/v1/me/decisions')).json()).items[0]).toEqual(original);
  await saved.getByRole('link').click();
  await expect(page.getByLabel('비교 기간')).toHaveValue('2022');
  await expect(page.getByLabel('가정 투자금')).toHaveValue('1000000');
  await expect(page.getByText(won(response.personalized.end_value),{exact:true})).toBeVisible();
  await page.reload();await expect(page.getByLabel('비교 기간')).toHaveValue('2022');
  await page.goto(review);
  await expect(page.getByRole('listitem').filter({hasText:reason})).toBeVisible();
  await expect(page.getByLabel('선택 이유')).toHaveValue('');
  expect(counts()).toEqual({...before,portfolio_choices:before.portfolio_choices+1});
  expect(errors).toEqual([]);
});
